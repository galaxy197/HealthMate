def vietnamese_name(description, category, fdc_id, *, heads=None):
    head = description.split(',')[0].strip()
    label = (HEADS if heads is None else heads).get(head.lower())
    if label is None:
        # Proper names/brands/rare varieties remain identifiable alongside a
        # Vietnamese food group. No fabricated translation of a brand.
        label = f'{category} · {head}'
    rest = description[len(head):].lower()
    details = []
    for term, vi in DETAILS.items():
        if re.search(r'\b' + re.escape(term) + r'\b', rest):
            details.append(vi)
            rest = re.sub(r'\b' + re.escape(term) + r'\b', '', rest)
    value = ' · '.join([label, *dict.fromkeys(details)])
    # Keep records distinct when a concise translation omits grade/cut details.
    suffix = f' · {fdc_id}'
    return value[:100-len(suffix)].rstrip(' ·') + suffix
