import 'dart:convert';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:http/http.dart' as http;

/// Consume the actual emulator email link, never mark the user verified by fiat.
/// This helper refuses cloud projects and non-loopback/emulator hostnames.
Future<void> verifyEmulatorEmail(
  FirebaseAuth auth, {
  required String projectId,
  String host = '10.0.2.2',
  bool send = true,
  bool reload = true,
}) async {
  if (!projectId.startsWith('demo-') ||
      !['10.0.2.2', '127.0.0.1', 'localhost'].contains(host) ||
      auth.app.options.projectId != projectId) {
    throw StateError(
      'Email fixture verification requires an explicit local demo backend.',
    );
  }
  final user = auth.currentUser;
  if (user == null) throw StateError('No emulator user to verify.');
  if (send) await user.sendEmailVerification();
  String? code;
  for (var attempt = 0; attempt < 30 && code == null; attempt++) {
    final r = await http.get(
      Uri.parse('http://$host:9099/emulator/v1/projects/$projectId/oobCodes'),
    );
    if (r.statusCode != 200) {
      throw StateError('Cannot read emulator email actions.');
    }
    final messages =
        (jsonDecode(r.body) as Map<String, dynamic>)['oobCodes'] as List? ??
        const [];
    for (final m in messages.reversed) {
      if (m['email'] == user.email && m['requestType'] == 'VERIFY_EMAIL') {
        code = m['oobCode'] as String;
        break;
      }
    }
    if (code == null) {
      await Future<void>.delayed(const Duration(milliseconds: 150));
    }
  }
  if (code == null) {
    throw StateError('Verification email was not generated by the emulator.');
  }
  final response = await http.post(
    Uri.parse(
      'http://$host:9099/identitytoolkit.googleapis.com/v1/accounts:update?key=demo-key',
    ),
    headers: {'Content-Type': 'application/json'},
    body: jsonEncode({'oobCode': code}),
  );
  if (response.statusCode != 200) {
    throw StateError('Emulator verification link was rejected.');
  }
  if (reload) {
    await user.reload();
    await auth.currentUser!.getIdToken(true);
  }
}
